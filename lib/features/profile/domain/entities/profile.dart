class Profile {
  final String name;
  final String email;
  final String phone;
  final String address;
  final DateTime birthDate;
  final String dni;
  final String occupation;
  final String avatarUrl;

  Profile({
    required this.name,
    required this.email,
    required this.phone,
    required this.address,
    required this.birthDate,
    required this.dni,
    required this.occupation,
    required this.avatarUrl,
  });
}
